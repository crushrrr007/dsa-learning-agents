def main() -> None:
    missing = []
    for path in sorted(PROBLEMS.glob("*.json")):
        data = json.loads(path.read_text())
        pid = data["id"]
        if pid not in VIVA:
            missing.append(pid)
            continue
        data["viva"] = VIVA[pid]
        path.write_text(json.dumps(data, indent=2) + "\n")
    if missing:
        raise SystemExit(f"missing viva for: {missing}")
    print(f"rewrote viva for {len(VIVA)} problems")


if __name__ == "__main__":
    main()
